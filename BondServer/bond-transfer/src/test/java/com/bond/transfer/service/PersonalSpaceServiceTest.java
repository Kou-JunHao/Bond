package com.bond.transfer.service;

import com.baomidou.mybatisplus.core.conditions.Wrapper;
import com.bond.common.entity.User;
import com.bond.common.entity.Workspace;
import com.bond.common.entity.WorkspaceMember;
import com.bond.common.enums.WorkspaceRole;
import com.bond.common.enums.WorkspaceType;
import com.bond.transfer.mapper.UserMapper;
import com.bond.transfer.mapper.WorkspaceMapper;
import com.bond.transfer.mapper.WorkspaceMemberMapper;
import com.bond.transfer.entitlement.EntitlementResolver;
import com.bond.transfer.entitlement.Entitlements;
import com.bond.transfer.entitlement.PlanLimits;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.extension.ExtendWith;
import org.mockito.ArgumentCaptor;
import org.mockito.InjectMocks;
import org.mockito.Mock;
import org.mockito.junit.jupiter.MockitoExtension;
import org.springframework.dao.DuplicateKeyException;

import java.util.List;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.assertTrue;
import static org.mockito.ArgumentMatchers.any;
import static org.mockito.ArgumentMatchers.anyLong;
import static org.mockito.ArgumentMatchers.eq;
import static org.mockito.Mockito.lenient;
import static org.mockito.Mockito.never;
import static org.mockito.Mockito.times;
import static org.mockito.Mockito.verify;
import static org.mockito.Mockito.when;

/**
 * 个人空间解析/创建的单测（Mock 掉 mapper，不依赖 PG）。
 * 覆盖任务要求的三点：创建、重复调用幂等、并发唯一键兜底、启动回填只补缺失用户。
 */
@ExtendWith(MockitoExtension.class)
class PersonalSpaceServiceTest {

    private static final long DEFAULT_MAX_SIZE = 5368709120L;

    @Mock
    private WorkspaceMapper workspaceMapper;
    @Mock
    private WorkspaceMemberMapper memberMapper;
    @Mock
    private UserMapper userMapper;
    @Mock
    private ConfigService configService;
    @Mock
    private EntitlementResolver entitlementResolver;

    @InjectMocks
    private PersonalSpaceService personalSpaceService;

    @BeforeEach
    void stubDefaultQuota() {
        lenient().when(configService.getLong(eq("workspace.max_size"), anyLong())).thenReturn(DEFAULT_MAX_SIZE);
        lenient().when(entitlementResolver.resolve(anyLong()))
                .thenReturn(new Entitlements("free", PlanLimits.FREE_DEFAULTS, null));
    }

    @Test
    @DisplayName("首次访问：创建 type=personal 的个人空间 + OWNER 成员行，id 由雪花生成")
    void createsPersonalSpaceWhenMissing() {
        when(workspaceMapper.selectOne(any(Wrapper.class))).thenReturn(null);
        when(memberMapper.selectCount(any(Wrapper.class))).thenReturn(0L);

        PersonalSpaceService.EnsureResult result = personalSpaceService.ensurePersonalSpace(42L);

        assertTrue(result.created());
        ArgumentCaptor<Workspace> wsCaptor = ArgumentCaptor.forClass(Workspace.class);
        verify(workspaceMapper).insert(wsCaptor.capture());
        Workspace ws = wsCaptor.getValue();
        assertNotNull(ws.getId(), "personal workspace id must be generated by SnowflakeId");
        assertEquals(42L, ws.getOwnerId());
        assertEquals(WorkspaceType.PERSONAL.getValue(), ws.getType());
        assertEquals(DEFAULT_MAX_SIZE, ws.getMaxSize());
        assertEquals(0L, ws.getUsedSize());
        assertEquals(ws.getId(), result.workspaceId());

        ArgumentCaptor<WorkspaceMember> memberCaptor = ArgumentCaptor.forClass(WorkspaceMember.class);
        verify(memberMapper).insert(memberCaptor.capture());
        WorkspaceMember member = memberCaptor.getValue();
        assertNotNull(member.getId());
        assertEquals(ws.getId(), member.getWorkspaceId());
        assertEquals(42L, member.getUserId());
        assertEquals(WorkspaceRole.OWNER.getValue(), member.getRole());
    }

    @Test
    @DisplayName("重复调用：个人空间已存在时不重复创建（幂等）")
    void repeatedEnsureDoesNotCreateDuplicate() {
        Workspace existing = personalWorkspace(999L, 42L);
        when(workspaceMapper.selectOne(any(Wrapper.class))).thenReturn(existing);
        when(memberMapper.selectCount(any(Wrapper.class))).thenReturn(1L);

        PersonalSpaceService.EnsureResult first = personalSpaceService.ensurePersonalSpace(42L);
        PersonalSpaceService.EnsureResult second = personalSpaceService.ensurePersonalSpace(42L);

        assertFalse(first.created());
        assertFalse(second.created());
        assertEquals(999L, first.workspaceId());
        assertEquals(999L, second.workspaceId());
        verify(workspaceMapper, never()).insert(any(Workspace.class));
        verify(memberMapper, never()).insert(any(WorkspaceMember.class));
    }

    @Test
    @DisplayName("并发创建撞 ux_workspaces_personal_owner：回查已有行，不抛异常")
    void concurrentInsertFallsBackToExistingRow() {
        Workspace winner = personalWorkspace(1000L, 7L);
        when(workspaceMapper.selectOne(any(Wrapper.class))).thenReturn(null, winner);
        when(workspaceMapper.insert(any(Workspace.class)))
                .thenThrow(new DuplicateKeyException("duplicate key ux_workspaces_personal_owner"));
        when(memberMapper.selectCount(any(Wrapper.class))).thenReturn(1L);

        PersonalSpaceService.EnsureResult result = personalSpaceService.ensurePersonalSpace(7L);

        assertFalse(result.created());
        assertEquals(1000L, result.workspaceId());
        verify(workspaceMapper, times(1)).insert(any(Workspace.class));
    }

    @Test
    @DisplayName("启动回填：已有个人空间的用户跳过，只为缺失用户创建")
    void backfillCreatesOnlyMissingUsers() {
        Workspace existing = personalWorkspace(1L, 1L);
        User userWithSpace = new User();
        userWithSpace.setId(1L);
        User userWithoutSpace = new User();
        userWithoutSpace.setId(2L);

        when(workspaceMapper.selectList(any(Wrapper.class))).thenReturn(List.of(existing));
        when(userMapper.selectList(any())).thenReturn(List.of(userWithSpace, userWithoutSpace));
        when(workspaceMapper.selectOne(any(Wrapper.class))).thenReturn(null);
        when(memberMapper.selectCount(any(Wrapper.class))).thenReturn(0L);

        int created = personalSpaceService.backfillMissingPersonalSpaces();

        assertEquals(1, created);
        ArgumentCaptor<Workspace> captor = ArgumentCaptor.forClass(Workspace.class);
        verify(workspaceMapper, times(1)).insert(captor.capture());
        assertEquals(2L, captor.getValue().getOwnerId());
        assertEquals(WorkspaceType.PERSONAL.getValue(), captor.getValue().getType());
    }

    private static Workspace personalWorkspace(long id, long ownerId) {
        Workspace ws = new Workspace();
        ws.setId(id);
        ws.setOwnerId(ownerId);
        ws.setType(WorkspaceType.PERSONAL.getValue());
        ws.setName("个人空间");
        ws.setMaxSize(DEFAULT_MAX_SIZE);
        ws.setUsedSize(0L);
        return ws;
    }
}
